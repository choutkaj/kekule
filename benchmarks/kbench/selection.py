"""Shared machinery for maintainers' dataset selection.

A dataset's `select.py` exposes `select(context) -> list[Record]`. It writes
every fetched file through `Context.stage`, which records the upstream URL and
SHA-256, and puts what it resolved (releases, pool sizes and hashes) into
`context.lock`. `run` then writes the manifest, the lock and the curated tier.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import shutil
import tomllib
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from .datasets import DATASETS, MANIFEST_SCHEMA, Record, SourceFile, cache_root, safe_member, sha256_bytes
from .upstream import Client, rng


@dataclass
class Context:
    """State passed to a dataset's `select` function."""

    name: str
    directory: Path
    selection: dict
    staging: Path
    client: Client
    lock: dict = field(default_factory=dict)

    @property
    def seed(self) -> int:
        return int(self.selection["dataset"]["seed"])

    def strata(self, source: str) -> list[dict]:
        return [stratum for stratum in self.selection["stratum"] if stratum["source"] == source]

    def rng(self, stratum: str):
        return rng(self.seed, stratum)

    def stage(self, path: str, data: bytes, format: str, url: str, role=None, row=None) -> SourceFile:
        if not safe_member(path):
            raise ValueError(f"unsafe dataset path {path!r}")
        target = self.staging / path
        if target.exists() and target.read_bytes() != data:
            raise ValueError(f"{path} staged twice with different content")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        return SourceFile(path, format, sha256_bytes(data), url, role, row)


def load_select(directory: Path):
    spec = importlib.util.spec_from_file_location(f"select_{directory.name}", directory / "select.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.select


def run(name: str, client: Client | None = None) -> list[Record]:
    directory = DATASETS / name
    with open(directory / "selection.toml", "rb") as handle:
        selection = tomllib.load(handle)
    staging = cache_root() / "staging" / name / f"v{selection['dataset']['version']}"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    client = client or Client(cache=cache_root() / "http" / name)
    context = Context(name, directory, selection, staging, client)
    context.lock = {"schema": 1, "dataset": name, "selected": date.today().isoformat(), "strata": {}}
    records = load_select(directory)(context)
    check_quotas(selection, records)
    write_manifest(directory, name, records)
    sizes = {record.id: (staging / record.files[0].path).stat().st_size for record in records}
    curated = choose_curated(selection, records, sizes)
    (directory / "curated.txt").write_text(
        "# Curated tier: generated by `bench.py select`; see selection.toml.\n"
        + "".join(f"{record_id}\n" for record_id in curated),
        encoding="utf-8",
        newline="\n",
    )
    copy_curated(directory / "curated", staging, [r for r in records if r.id in set(curated)])
    write_lock(directory, context.lock)
    return records


def check_quotas(selection: dict, records: list[Record]) -> None:
    counts: dict[str, int] = {}
    for record in records:
        counts[record.stratum] = counts.get(record.stratum, 0) + 1
    for stratum in selection["stratum"]:
        quota = stratum.get("quota")
        if quota is not None and counts.get(stratum["id"], 0) != quota:
            raise ValueError(f"{stratum['id']}: selected {counts.get(stratum['id'], 0)} of {quota}")


def write_manifest(directory: Path, name: str, records: list[Record]) -> None:
    lines = [json.dumps({"schema": MANIFEST_SCHEMA, "dataset": name}, separators=(",", ":"))]
    lines += [json.dumps(record.to_json(), separators=(",", ":"), ensure_ascii=False) for record in records]
    (directory / "manifest.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def write_lock(directory: Path, lock: dict) -> None:
    path = directory / "selection.lock.json"
    previous = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    if "snapshot" in previous and "snapshot" not in lock:
        lock["snapshot"] = previous["snapshot"]
    path.write_text(json.dumps(lock, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def choose_curated(selection: dict, records: list[Record], sizes: dict[str, int]) -> list[str]:
    """Per stratum: the smallest few by primary file size, then seeded random picks."""
    smallest = int(selection["dataset"]["curated_smallest"])
    random_count = int(selection["dataset"]["curated_random"])
    chosen: list[str] = []
    for stratum in selection["stratum"]:
        members = [record for record in records if record.stratum == stratum["id"]]
        if stratum.get("curated") == "all":
            chosen += [record.id for record in members]
            continue
        forced = [record.id for record in members if record.source_id in stratum.get("include", [])]
        by_size = sorted(members, key=lambda record: (sizes[record.id], record.id))
        picks = list(dict.fromkeys(forced + [record.id for record in by_size[:smallest]]))
        rest = sorted(record.id for record in members if record.id not in picks)
        picks += rng(int(selection["dataset"]["seed"]), "curated:" + stratum["id"]).sample(
            rest, min(random_count, len(rest))
        )
        chosen += sorted(picks)
    return chosen


def copy_curated(target: Path, staging: Path, records: list[Record]) -> None:
    if target.exists():
        shutil.rmtree(target)
    for path in sorted({file.path for record in records for file in record.files}):
        destination = target / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(staging / path, destination)


def pool_hash(identifiers) -> str:
    """Order-independent SHA-256 of a candidate pool's identifiers."""
    return hashlib.sha256("\n".join(sorted(map(str, identifiers))).encode()).hexdigest()
