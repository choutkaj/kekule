"""Generates the one-letter codes of the dictionary's polymer components.

Run from the repository root:

    python tools/components/codes.py                        # download and generate
    python tools/components/codes.py --source components.cif.gz

The source is the complete wwPDB Chemical Component Dictionary
(`components.cif.gz`), which is public domain (CC0 1.0). The output,
`crates/kekule/data/components/codes.tsv`, lists every component whose type
links it into a polypeptide or a polynucleotide, with its one-letter code and
parents. `codes.lock.json` records the source's checksum and release.
"""
import argparse
import gzip
import hashlib
import json
import re
import shlex
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUTPUT = ROOT / "crates/kekule/data/components/codes.tsv"
LOCK = HERE / "codes.lock.json"
URL = "https://files.wwpdb.org/pub/pdb/data/monomers/components.cif.gz"
ITEMS = ("id", "type", "one_letter_code", "mon_nstd_parent_comp_id", "pdbx_modified_date")
HEADER = """\
# One-letter codes of the polymer components of the wwPDB Chemical Component
# Dictionary (CC0 1.0), generated by tools/components/codes.py; do not edit.
# Columns: identifier, linking (P peptide, N nucleotide), one-letter code
# (empty when the dictionary states none), parent identifiers.
"""


def linking(kind):
    """`P` or `N` as `ComponentLinking::from_type` classifies the type, else None."""
    kind = kind.upper()
    if "PEPTIDE" in kind and ("LINKING" in kind or "TERMINUS" in kind) and "PEPTIDE-LIKE" not in kind:
        return "P"
    if "DNA" in kind or "RNA" in kind:
        return "N"
    return None


def unknown(value):
    return value is None or value in ("?", ".")


def components(path):
    """The `_chem_comp` items of every data block, as dictionaries."""
    current = None
    with gzip.open(path, "rt", encoding="utf-8") as text:
        for line in text:
            if line.startswith("data_"):
                if current is not None:
                    yield current
                current = {}
            elif line.startswith("_chem_comp.") and current is not None:
                tag, _, rest = line.partition(" ")
                item = tag[len("_chem_comp."):]
                if item in ITEMS:
                    values = shlex.split(rest, posix=True) if rest.strip() else []
                    if len(values) != 1:
                        raise ValueError(f"unexpected value for {tag}: {rest!r}")
                    current[item] = values[0]
    if current is not None:
        yield current


def rows(path):
    table = []
    for component in components(path):
        kind = linking(component.get("type", ""))
        if kind is None:
            continue
        identifier = component["id"]
        code = component.get("one_letter_code")
        code = "" if unknown(code) else code
        if not re.fullmatch(r"[A-Z]*", code):
            raise ValueError(f"{identifier}: unexpected one-letter code {code!r}")
        parents = component.get("mon_nstd_parent_comp_id")
        parents = "" if unknown(parents) else ",".join(
            parent.strip() for parent in parents.split(",") if parent.strip()
        )
        table.append((identifier, kind, code, parents))
    table.sort()
    return table


def render(table):
    return HEADER + "".join("\t".join(row) + "\n" for row in table)


def release(path):
    """The latest modification date in the dictionary."""
    return max(
        component.get("pdbx_modified_date", "")
        for component in components(path)
    )


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="a downloaded components.cif.gz")
    arguments = parser.parse_args()
    source = arguments.source
    if source is None:
        source = HERE / "components.cif.gz"
        with urllib.request.urlopen(URL, timeout=600) as response:
            source.write_bytes(response.read())
    OUTPUT.write_text(render(rows(source)), encoding="utf-8", newline="\n")
    record = {
        "schema": 1,
        "source": "wwPDB Chemical Component Dictionary (components.cif.gz)",
        "license": "CC0 1.0 (wwPDB archive data)",
        "url": URL,
        "sha256": digest(source),
        "latest_modified": release(source),
        "output": OUTPUT.relative_to(ROOT).as_posix(),
        "output_sha256": digest(OUTPUT),
    }
    LOCK.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
