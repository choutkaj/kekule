"""Generates the formal-charge table of the complete Chemical Component Dictionary.

Run from the repository root:

    python tools/components/charges.py                        # download and generate
    python tools/components/charges.py --source components.cif.gz

The source is the complete wwPDB Chemical Component Dictionary
(`components.cif.gz`), which is public domain (CC0 1.0). The output,
`crates/kekule/data/components/charges.tsv`, lists every component with a
nonzero or unknown (`?`) atom charge, with the charge of each of its atoms
other than uncharged hydrogens. `charges.lock.json` records the
source's checksum and release.
"""
import argparse
import gzip
import hashlib
import json
import re
import tempfile
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUTPUT = ROOT / "crates/kekule/data/components/charges.tsv"
LOCK = HERE / "charges.lock.json"
URL = "https://files.wwpdb.org/pub/pdb/data/monomers/components.cif.gz"
HEADER = """\
# Formal charges of the wwPDB Chemical Component Dictionary (CC0 1.0),
# generated by tools/components/charges.py; do not edit.
# Release: entries modified up to {release}.
# Rows: identifier, then each atom other than an uncharged hydrogen: its name,
# `/` and its element unless that is the name's first letter, and `=` and its
# charge unless that is zero, or `=?` where the dictionary states none.
"""
ATOM_ITEMS = ("comp_id", "atom_id", "type_symbol", "charge")
NAME = re.compile(r"[!-~]+")
ELEMENT = re.compile(r"[A-Z]{1,2}")


def tokens(line):
    """The CIF tokens of one line; quoted tokens end at a quote before a space."""
    found = []
    index = 0
    while index < len(line):
        if line[index].isspace():
            index += 1
            continue
        quote = line[index]
        if quote in "'\"":
            end = index + 1
            while True:
                end = line.find(quote, end)
                if end < 0:
                    raise ValueError(f"unterminated quoted value in {line!r}")
                if end + 1 == len(line) or line[end + 1].isspace():
                    break
                end += 1
            found.append(line[index + 1:end])
            index = end + 1
        else:
            end = index
            while end < len(line) and not line[end].isspace():
                end += 1
            found.append(line[index:end])
            index = end
    return found


def components(path):
    """Each data block's `_chem_comp` id and modification date, and atoms.

    Atoms are `(name, element, charge)`, with `None` for a `?` charge.
    """
    with gzip.open(path, "rt", encoding="utf-8") as text:
        yield from blocks(line.rstrip("\r\n") for line in text)


def blocks(lines):
    """The components of the CIF text `lines` (see `components`)."""
    lines = iter(lines)
    current = None
    line = next(lines, None)
    while line is not None:
        if line.startswith(";"):
            # A text field runs to the next line that starts with `;`.
            line = next(lines, None)
            while line is not None and not line.startswith(";"):
                line = next(lines, None)
        elif line.startswith("data_"):
            if current is not None:
                yield current
            current = {"atoms": [], "single": {}}
        elif current is None:
            pass
        elif line.startswith(("_chem_comp.id ", "_chem_comp.pdbx_modified_date ")):
            tag, value = tokens(line)
            current[tag[len("_chem_comp."):]] = value
        elif line.startswith("_chem_comp_atom."):
            tag, value = tokens(line)
            current["single"][tag[len("_chem_comp_atom."):]] = value
        elif line.strip() == "loop_":
            tags = []
            line = next(lines, None)
            while line is not None and line.startswith("_"):
                tags.append(line.strip())
                line = next(lines, None)
            if tags and tags[0].startswith("_chem_comp_atom."):
                columns = [tags.index(f"_chem_comp_atom.{item}") for item in ATOM_ITEMS]
                values = []
                while line is not None and not line.startswith(("#", "_", "loop_", "data_")):
                    if line.startswith(";"):
                        raise ValueError("a text field inside _chem_comp_atom")
                    values.extend(tokens(line))
                    line = next(lines, None)
                if len(values) % len(tags):
                    raise ValueError(f"ragged _chem_comp_atom loop in {current.get('id')}")
                for start in range(0, len(values), len(tags)):
                    row = values[start:start + len(tags)]
                    current["atoms"].append(tuple(row[column] for column in columns))
            # The line that ends the loop is read like any other.
            continue
        line = next(lines, None)
    if current is not None:
        yield current


def charge(value):
    return None if value in ("?", ".") else int(value)


def entries(path):
    """`(identifier, atoms, release date)` of every component."""
    for component in components(path):
        atoms = component["atoms"]
        single = component["single"]
        if not atoms and single:
            atoms = [tuple(single[item] for item in ATOM_ITEMS)]
        identifier = component["id"]
        rows = []
        for comp_id, name, element, value in atoms:
            if comp_id != identifier:
                raise ValueError(f"{identifier}: atom {name} of {comp_id}")
            rows.append((name, element.upper(), charge(value)))
        yield identifier, rows, component.get("pdbx_modified_date", "")


def is_hydrogen(element):
    return element in ("H", "D")


def rows(path):
    """The table rows and the latest modification date."""
    table = []
    release = ""
    for identifier, atoms, modified in entries(path):
        release = max(release, modified)
        if all(value == 0 for _, _, value in atoms):
            continue
        fields = [identifier]
        for name, element, value in atoms:
            if not NAME.fullmatch(name) or "=" in name or "/" in name:
                raise ValueError(f"{identifier}: unexpected atom name {name!r}")
            if not ELEMENT.fullmatch(element):
                raise ValueError(f"{identifier}: unexpected element {element!r}")
            if is_hydrogen(element) and value == 0:
                continue
            field = name if name[0] == element else f"{name}/{element}"
            if value is None:
                field += "=?"
            elif value != 0:
                field += f"={value:+d}"
            fields.append(field)
        table.append(tuple(fields))
    table.sort()
    return table, release


def render(table, release):
    return HEADER.format(release=release) + "".join("\t".join(row) + "\n" for row in table)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="a downloaded components.cif.gz")
    arguments = parser.parse_args()
    if arguments.source is not None:
        generate(arguments.source)
        return
    # The download is not kept, so it cannot be committed.
    with tempfile.TemporaryDirectory() as directory:
        source = Path(directory) / "components.cif.gz"
        with urllib.request.urlopen(URL, timeout=600) as response:
            source.write_bytes(response.read())
        generate(source)


def generate(source):
    """Writes the table and its lock from the dictionary at `source`."""
    table, release = rows(source)
    OUTPUT.write_text(render(table, release), encoding="utf-8", newline="\n")
    record = {
        "schema": 1,
        "source": "wwPDB Chemical Component Dictionary (components.cif.gz)",
        "license": "CC0 1.0 (wwPDB archive data)",
        "url": URL,
        "sha256": digest(source),
        "latest_modified": release,
        "output": OUTPUT.relative_to(ROOT).as_posix(),
        "output_sha256": digest(OUTPUT),
    }
    LOCK.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
