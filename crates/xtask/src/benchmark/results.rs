use crate::*;

pub(crate) fn read_benchmark_results(
    features: &[Feature],
) -> Result<BTreeMap<String, BenchmarkResults>, Box<dyn Error>> {
    let mut results = BTreeMap::new();
    for corpus in BENCHMARK_CORPORA {
        let path = benchmark_results_path(corpus.id);
        if !path.exists() {
            continue;
        }
        let file = read_corpus_results(&path)?;
        if file.corpus_id != corpus.id {
            return Err(boxed_error(format!(
                "{} declares corpus_id `{}`, expected `{}`",
                path.display(),
                file.corpus_id,
                corpus.id
            )));
        }
        for (feature_id, result) in file.features {
            if !features.iter().any(|feature| feature.id == feature_id) {
                return Err(boxed_error(format!(
                    "{} records unknown feature `{feature_id}`",
                    path.display()
                )));
            }
            results
                .entry(feature_id.clone())
                .or_insert_with(|| BenchmarkResults::new(&feature_id))
                .corpora
                .insert(corpus.id.to_owned(), result);
        }
    }
    Ok(results)
}

pub(crate) fn benchmark_results_path(corpus: &str) -> PathBuf {
    benchmark_results_path_from(Path::new("."), corpus)
}

pub(crate) fn benchmark_results_path_from(root: &Path, corpus: &str) -> PathBuf {
    root.join("benchmarks")
        .join("corpora")
        .join(corpus)
        .join("results.toml")
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct CorpusResultsFile {
    pub(crate) corpus_id: String,
    #[serde(default)]
    pub(crate) features: BTreeMap<String, BenchmarkResult>,
}

pub(crate) fn read_corpus_results(path: &Path) -> Result<CorpusResultsFile, Box<dyn Error>> {
    let text = fs::read_to_string(path)?;
    toml::from_str(&text).map_err(|error| boxed_error(format!("{}: {error}", path.display())))
}

pub(crate) fn write_benchmark_results(
    results: &BTreeMap<String, BenchmarkResults>,
    selected_corpora: &BTreeSet<String>,
) -> Result<(), Box<dyn Error>> {
    write_benchmark_results_from(Path::new("."), results, selected_corpora)
}

pub(crate) fn write_benchmark_results_from(
    root: &Path,
    results: &BTreeMap<String, BenchmarkResults>,
    selected_corpora: &BTreeSet<String>,
) -> Result<(), Box<dyn Error>> {
    for corpus in BENCHMARK_CORPORA {
        if !selected_corpora.contains(corpus.id) {
            continue;
        }
        let mut file = CorpusResultsFile {
            corpus_id: corpus.id.to_owned(),
            features: BTreeMap::new(),
        };
        for (feature_id, result) in results {
            if !benchmark_manifest_path_from(root, feature_id, corpus.id).exists() {
                continue;
            }
            if let Some(snapshot) = result.corpora.get(corpus.id) {
                file.features.insert(feature_id.clone(), snapshot.clone());
            }
        }
        let path = benchmark_results_path_from(root, corpus.id);
        if file.features.is_empty() {
            if path.exists() {
                fs::remove_file(&path)?;
            }
            continue;
        }
        fs::create_dir_all(
            path.parent()
                .ok_or_else(|| boxed_error("results path has no parent"))?,
        )?;
        let text = toml::to_string_pretty(&file)?;
        write_atomic_text(
            &path,
            &format!("# Generated by `cargo xtask benchmark`. Do not hand-edit.\n{text}"),
        )?;
    }
    Ok(())
}

pub(crate) fn write_atomic_text(path: &Path, text: &str) -> Result<(), Box<dyn Error>> {
    write_atomic_bytes(path, text.as_bytes())
}

pub(crate) fn write_atomic_bytes(path: &Path, bytes: &[u8]) -> Result<(), Box<dyn Error>> {
    let parent = path
        .parent()
        .ok_or_else(|| boxed_error(format!("{} has no parent", path.display())))?;
    fs::create_dir_all(parent)?;
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| boxed_error(format!("{} has no file name", path.display())))?;
    let nonce = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
    let tmp = parent.join(format!(".{file_name}.{nonce}.tmp"));
    fs::write(&tmp, bytes)?;
    match fs::rename(&tmp, path) {
        Ok(()) => Ok(()),
        Err(error) if path.exists() => {
            fs::remove_file(path)?;
            fs::rename(&tmp, path).map_err(|rename_error| {
                boxed_error(format!(
                    "failed to replace {} after initial rename error {error}: {rename_error}",
                    path.display()
                ))
            })
        }
        Err(error) => Err(boxed_error(format!(
            "failed to replace {}: {error}",
            path.display()
        ))),
    }
}
